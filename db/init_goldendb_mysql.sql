SET NAMES utf8mb4;
SET FOREIGN_KEY_CHECKS = 0;

-- 1. 创建数据库（按需执行，若企业已有命名空间/Schema，可直接使用对应库名）
CREATE DATABASE IF NOT EXISTS `im_platform_open` DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_general_ci;
USE `im_platform_open`;

-- ----------------------------
-- 表 1: 用户表 (im_user)
-- ----------------------------
DROP TABLE IF EXISTS `im_user`;
CREATE TABLE `im_user` (
  `id` bigint NOT NULL AUTO_INCREMENT COMMENT '用户主键ID',
  `user_name` varchar(255) NOT NULL COMMENT '用户名',
  `nick_name` varchar(255) NOT NULL COMMENT '用户昵称',
  `head_image` varchar(255) DEFAULT '' COMMENT '用户头像',
  `head_image_thumb` varchar(255) DEFAULT '' COMMENT '用户头像缩略图',
  `password` varchar(255) NOT NULL COMMENT '密码（BCrypt密文）',
  `sex` tinyint DEFAULT 0 COMMENT '性别 0:男 1:女',
  `is_banned` tinyint(1) DEFAULT 0 COMMENT '是否被封禁 0:否 1:是',
  `reason` varchar(255) DEFAULT '' COMMENT '被封禁原因',
  `type` smallint DEFAULT 1 COMMENT '用户类型 1:普通用户 2:审核账户',
  `signature` varchar(1024) DEFAULT '' COMMENT '个性签名',
  `last_login_time` datetime DEFAULT NULL COMMENT '最后登录时间',
  `created_time` datetime DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  PRIMARY KEY (`id`),
  UNIQUE KEY `idx_user_name` (`user_name`),
  KEY `idx_nick_name` (`nick_name`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci COMMENT='用户表';

-- ----------------------------
-- 表 2: 好友关系表 (im_friend)
-- ----------------------------
DROP TABLE IF EXISTS `im_friend`;
CREATE TABLE `im_friend` (
  `id` bigint NOT NULL AUTO_INCREMENT COMMENT '关系主键ID',
  `user_id` bigint NOT NULL COMMENT '用户ID',
  `friend_id` bigint NOT NULL COMMENT '好友ID',
  `friend_nick_name` varchar(255) NOT NULL COMMENT '好友昵称',
  `friend_head_image` varchar(255) DEFAULT '' COMMENT '好友头像',
  `is_dnd` tinyint DEFAULT 0 COMMENT '免打扰标识 0:关闭 1:开启',
  `is_top` tinyint(1) DEFAULT 0 COMMENT '是否置顶会话',
  `deleted` tinyint DEFAULT 0 COMMENT '删除标识 0:正常 1:已删除',
  `created_time` datetime DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  `version` bigint DEFAULT 0 COMMENT '增量同步版本号',
  PRIMARY KEY (`id`),
  UNIQUE KEY `idx_user_friend_id` (`user_id`, `friend_id`),
  KEY `idx_friend_id` (`friend_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci COMMENT='好友关系表';

-- ----------------------------
-- 表 3: 私聊消息表 (im_private_message)
-- ----------------------------
DROP TABLE IF EXISTS `im_private_message`;
CREATE TABLE `im_private_message` (
  `id` bigint NOT NULL AUTO_INCREMENT COMMENT '消息主键ID',
  `local_id` varchar(32) DEFAULT NULL COMMENT '业务ID（前端生成雪花/临时ID）',
  `seq_no` bigint NOT NULL COMMENT '会话连续递增序列号',
  `send_id` bigint NOT NULL COMMENT '发送者ID',
  `recv_id` bigint NOT NULL COMMENT '接收者ID',
  `conv_key` varchar(64) NOT NULL COMMENT '会话Key (userId1_userId2)',
  `content` text COMMENT '消息内容',
  `type` tinyint NOT NULL COMMENT '消息类型 0:文字 1:图片 2:文件 3:语音 4:视频 21:提示',
  `status` tinyint NOT NULL COMMENT '状态 0:未读 1:已发送 2:撤回 3:已读',
  `send_time` datetime(3) DEFAULT CURRENT_TIMESTAMP(3) COMMENT '发送时间（毫秒精度）',
  PRIMARY KEY (`id`),
  KEY `idx_conv_key_seq_no` (`conv_key`, `seq_no`),
  KEY `idx_send_recv_id` (`send_id`, `recv_id`, `id`),
  KEY `idx_recv_id` (`recv_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci COMMENT='私聊消息表';

-- ----------------------------
-- 表 4: 群聊表 (im_group)
-- ----------------------------
DROP TABLE IF EXISTS `im_group`;
CREATE TABLE `im_group` (
  `id` bigint NOT NULL AUTO_INCREMENT COMMENT '群主键ID',
  `name` varchar(255) NOT NULL COMMENT '群名称',
  `owner_id` bigint NOT NULL COMMENT '群主ID',
  `head_image` varchar(255) DEFAULT '' COMMENT '群头像',
  `head_image_thumb` varchar(255) DEFAULT '' COMMENT '群头像缩略图',
  `notice` varchar(1024) DEFAULT '' COMMENT '群公告',
  `is_banned` tinyint(1) DEFAULT 0 COMMENT '是否被封禁 0:否 1:是',
  `reason` varchar(255) DEFAULT '' COMMENT '被封禁原因',
  `dissolve` tinyint(1) DEFAULT 0 COMMENT '是否已解散',
  `created_time` datetime DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  PRIMARY KEY (`id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci COMMENT='群聊表';

-- ----------------------------
-- 表 5: 群成员表 (im_group_member)
-- ----------------------------
DROP TABLE IF EXISTS `im_group_member`;
CREATE TABLE `im_group_member` (
  `id` bigint NOT NULL AUTO_INCREMENT COMMENT '主键ID',
  `group_id` bigint NOT NULL COMMENT '群ID',
  `user_id` bigint NOT NULL COMMENT '用户ID',
  `user_nick_name` varchar(255) DEFAULT '' COMMENT '用户群内昵称',
  `remark_nick_name` varchar(255) DEFAULT '' COMMENT '显示昵称备注',
  `head_image` varchar(255) DEFAULT '' COMMENT '用户头像',
  `remark_group_name` varchar(255) DEFAULT '' COMMENT '显示群名备注',
  `is_dnd` tinyint(1) DEFAULT 0 COMMENT '免打扰标识 0:关闭 1:开启',
  `is_top` tinyint(1) DEFAULT 0 COMMENT '是否置顶会话',
  `quit` tinyint(1) DEFAULT 0 COMMENT '是否已退出群聊',
  `quit_time` datetime DEFAULT NULL COMMENT '退出时间',
  `created_time` datetime DEFAULT CURRENT_TIMESTAMP COMMENT '加入时间',
  `version` bigint DEFAULT 0 COMMENT '增量同步版本号',
  PRIMARY KEY (`id`),
  KEY `idx_group_id` (`group_id`),
  KEY `idx_user_id` (`user_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci COMMENT='群成员表';

-- ----------------------------
-- 表 6: 群聊消息表 (im_group_message)
-- ----------------------------
DROP TABLE IF EXISTS `im_group_message`;
CREATE TABLE `im_group_message` (
  `id` bigint NOT NULL AUTO_INCREMENT COMMENT '消息主键ID',
  `local_id` varchar(32) DEFAULT NULL COMMENT '业务ID（前端生成）',
  `group_id` bigint NOT NULL COMMENT '群ID',
  `seq_no` bigint NOT NULL COMMENT '会话连续递增序列号',
  `send_id` bigint NOT NULL COMMENT '发送者用户ID',
  `send_nick_name` varchar(255) DEFAULT '' COMMENT '发送者昵称',
  `content` text COMMENT '发送内容',
  `at_user_ids` varchar(1024) DEFAULT NULL COMMENT '被@的用户ID列表（逗号分隔）',
  `receipt` tinyint(1) DEFAULT 0 COMMENT '是否回执消息',
  `receipt_ok` tinyint(1) DEFAULT 0 COMMENT '回执消息是否已确认完成',
  `type` tinyint NOT NULL COMMENT '消息类型 0:文字 1:图片 2:文件 3:语音 4:视频 21:提示',
  `status` tinyint DEFAULT 0 COMMENT '状态 0:未发出 2:撤回',
  `send_time` datetime(3) DEFAULT CURRENT_TIMESTAMP(3) COMMENT '发送时间（毫秒精度）',
  PRIMARY KEY (`id`),
  KEY `idx_group_id_seq_no` (`group_id`, `seq_no`),
  KEY `idx_send_time` (`send_time`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci COMMENT='群聊消息表';

-- ----------------------------
-- 表 7: 敏感词表 (im_sensitive_word)
-- ----------------------------
DROP TABLE IF EXISTS `im_sensitive_word`;
CREATE TABLE `im_sensitive_word` (
  `id` bigint NOT NULL AUTO_INCREMENT COMMENT '主键ID',
  `content` varchar(64) NOT NULL COMMENT '敏感词内容',
  `enabled` tinyint(1) DEFAULT 0 COMMENT '是否启用 0:未启用 1:启用',
  `creator` bigint DEFAULT NULL COMMENT '创建者ID',
  `create_time` datetime DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  PRIMARY KEY (`id`),
  KEY `idx_enabled` (`enabled`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci COMMENT='敏感词过滤表';

-- ----------------------------
-- 表 8: 文件媒体表 (im_file_info)
-- ----------------------------
DROP TABLE IF EXISTS `im_file_info`;
CREATE TABLE `im_file_info` (
  `id` bigint NOT NULL AUTO_INCREMENT COMMENT '主键ID',
  `file_name` varchar(255) NOT NULL COMMENT '文件名',
  `file_path` varchar(255) NOT NULL COMMENT '文件存储路径',
  `file_size` bigint NOT NULL COMMENT '文件大小（字节）',
  `file_type` tinyint NOT NULL COMMENT '文件类型 0:普通文件 1:图片 2:视频',
  `compressed_path` varchar(255) DEFAULT NULL COMMENT '压缩文件存储路径',
  `cover_path` varchar(255) DEFAULT NULL COMMENT '视频封面路径',
  `upload_time` datetime DEFAULT CURRENT_TIMESTAMP COMMENT '上传时间',
  `is_permanent` tinyint(1) DEFAULT 0 COMMENT '是否永久文件',
  `md5` varchar(64) NOT NULL COMMENT '文件MD5校验值',
  PRIMARY KEY (`id`),
  KEY `idx_md5` (`md5`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci COMMENT='文件存储信息表';

-- ----------------------------
-- 表 9: 消息删除记录表 (im_message_deletion)
-- ----------------------------
DROP TABLE IF EXISTS `im_message_deletion`;
CREATE TABLE `im_message_deletion` (
  `id` bigint NOT NULL AUTO_INCREMENT COMMENT '主键ID',
  `user_id` bigint NOT NULL COMMENT '用户ID',
  `chat_type` tinyint NOT NULL COMMENT '会话类型 1:私聊 2:群聊',
  `chat_id` bigint NOT NULL COMMENT '好友ID或群聊ID',
  `message_id` bigint DEFAULT NULL COMMENT '消息ID（按消息删除时填充）',
  `delete_type` tinyint NOT NULL COMMENT '删除类型 1:按消息删除 2:按会话删除',
  `delete_time` datetime DEFAULT CURRENT_TIMESTAMP COMMENT '删除时间',
  PRIMARY KEY (`id`),
  KEY `idx_user_id` (`user_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci COMMENT='消息删除记录表';

